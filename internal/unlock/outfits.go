// SortedOutfitIDs is the deduped, sorted unlock set, computed once.
// The unlock format requires sorted UUID bytes, so every generation path
// shares this single precomputed slice instead of re-sorting per click.
var SortedOutfitIDs []string

func init() {
	SortedOutfitIDs = make([]string, 0, len(AllOutfits))
	for id := range AllOutfits {
		SortedOutfitIDs = append(SortedOutfitIDs, id)
	}
	sort.Strings(SortedOutfitIDs)
}
